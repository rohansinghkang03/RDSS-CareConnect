BEGIN;
SELECT pg_advisory_xact_lock(301,8);
CREATE TABLE IF NOT EXISTS connection_request_drafts (
 sender TEXT PRIMARY KEY REFERENCES users(sender) ON DELETE CASCADE,
 buddy_id INTEGER NOT NULL,
 buddy_sender TEXT NOT NULL,
 preference_key TEXT NOT NULL,
 chosen_name TEXT CHECK(chosen_name IS NULL OR length(chosen_name) BETWEEN 1 AND 60),
 message TEXT CHECK(message IS NULL OR length(message)<=300),
 review_key TEXT,
 reviewed_at TIMESTAMPTZ,
 notice_version TEXT,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS connection_request_details (
 request_id INTEGER PRIMARY KEY REFERENCES match_requests(id) ON DELETE CASCADE,
 chosen_name TEXT NOT NULL CHECK(length(chosen_name) BETWEEN 1 AND 60),
 message TEXT NOT NULL CHECK(length(message)<=300),
 notice_version TEXT NOT NULL,
 shared_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS connection_accept_notices (
 request_id INTEGER NOT NULL REFERENCES match_requests(id) ON DELETE CASCADE,
 sender TEXT NOT NULL REFERENCES users(sender) ON DELETE CASCADE,
 pair_key TEXT NOT NULL,
 details_key TEXT NOT NULL,
 notice_version TEXT NOT NULL,
 shown_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(request_id,sender)
);
DO $$ BEGIN
 PERFORM sender,buddy_id,buddy_sender,preference_key,chosen_name,message,review_key,reviewed_at,notice_version,updated_at FROM connection_request_drafts LIMIT 0;
 PERFORM request_id,chosen_name,message,notice_version,shared_at FROM connection_request_details LIMIT 0;
 PERFORM request_id,sender,pair_key,details_key,notice_version,shown_at FROM connection_accept_notices LIMIT 0;
END $$;
-- Public nickname edits are independent of private identity and admin decisions.
CREATE TABLE IF NOT EXISTS buddy_profile_edit_drafts (
 sender TEXT PRIMARY KEY REFERENCES users(sender) ON DELETE CASCADE,
 application_id INTEGER NOT NULL REFERENCES support_buddy_applications(id) ON DELETE CASCADE,
 proposed_name TEXT NOT NULL,
 source_name TEXT,
 source_review_version INTEGER NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS buddy_profile_edits (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender TEXT NOT NULL REFERENCES users(sender) ON DELETE CASCADE,
 application_id INTEGER NOT NULL REFERENCES support_buddy_applications(id) ON DELETE CASCADE,
 old_name TEXT,
 new_name TEXT NOT NULL,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS buddy_whatsapp_consent (
 sender TEXT PRIMARY KEY REFERENCES users(sender) ON DELETE CASCADE,
 application_id INTEGER NOT NULL REFERENCES support_buddy_applications(id) ON DELETE CASCADE,
 status TEXT NOT NULL CHECK(status IN ('granted','revoked')),
 notice_version TEXT NOT NULL,
 consent_text TEXT NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE support_buddy_applications ADD COLUMN IF NOT EXISTS verified_by_name TEXT;
CREATE TABLE IF NOT EXISTS admin_verification_drafts (
 sender TEXT PRIMARY KEY REFERENCES users(sender) ON DELETE CASCADE,
 application_id INTEGER NOT NULL REFERENCES support_buddy_applications(id) ON DELETE CASCADE,
 review_version INTEGER NOT NULL,
 verifier_name TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
DO $$ BEGIN
 PERFORM sender,application_id,review_version,verifier_name,created_at FROM admin_verification_drafts LIMIT 0;
 PERFORM verified_by_name FROM support_buddy_applications LIMIT 0;
 PERFORM sender,application_id,proposed_name,source_name,source_review_version,created_at FROM buddy_profile_edit_drafts LIMIT 0;
 PERFORM id,sender,application_id,old_name,new_name,changed_at FROM buddy_profile_edits LIMIT 0;
 PERFORM sender,application_id,status,notice_version,consent_text,updated_at FROM buddy_whatsapp_consent LIMIT 0;
END $$;
COMMIT;
