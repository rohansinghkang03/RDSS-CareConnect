BEGIN;
SELECT pg_advisory_xact_lock(301,6);
CREATE TABLE IF NOT EXISTS notification_preferences (
 sender TEXT PRIMARY KEY REFERENCES users(sender) ON DELETE CASCADE,
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 last_inbound TIMESTAMPTZ,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS notification_outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient TEXT NOT NULL REFERENCES users(sender) ON DELETE CASCADE,
 event TEXT NOT NULL CHECK(event IN ('application_submitted','application_approved','application_rejected','application_verified','connection_request','connection_accepted','connection_declined','chat_ready')),
 entity_id INTEGER NOT NULL,
 event_key TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'queued' CHECK(state IN ('queued','sending','accepted','failed','unknown','cancelled')),
 provider_id TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(recipient,event,event_key)
);
CREATE INDEX IF NOT EXISTS notification_pending ON notification_outbox(state,created_at);
DO $$ BEGIN
 PERFORM sender,enabled,last_inbound,updated_at FROM notification_preferences LIMIT 0;
 PERFORM id,recipient,event,entity_id,event_key,state,provider_id,created_at,updated_at FROM notification_outbox LIMIT 0;
END $$;
COMMIT;
