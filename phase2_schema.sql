CREATE TABLE IF NOT EXISTS caregiver_profile_suggestions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender TEXT NOT NULL REFERENCES users(sender) ON DELETE CASCADE,
 field_name TEXT NOT NULL CHECK (field_name IN ('care_recipient_profile','support_needs','availability','caregiving_context')),
 proposed_value TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected')),
 pending_edit_value TEXT,
 reviewed_value TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reviewed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS profile_suggestions_sender_status ON caregiver_profile_suggestions(sender,status);
CREATE TABLE IF NOT EXISTS caregiver_profile_fields (
 sender TEXT NOT NULL REFERENCES users(sender) ON DELETE CASCADE,
 field_name TEXT NOT NULL CHECK (field_name IN ('care_recipient_profile','support_needs','availability','caregiving_context')),
 field_value TEXT NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (sender,field_name)
);
CREATE TABLE IF NOT EXISTS caregiver_sharing_decisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender TEXT NOT NULL REFERENCES users(sender) ON DELETE CASCADE,
 match_request_id INTEGER REFERENCES match_requests(id),
 decision TEXT NOT NULL CHECK (decision IN ('share','decline')),
 approved_summary TEXT,
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK ((decision='share' AND approved_summary IS NOT NULL AND length(trim(approved_summary))>0)
    OR (decision='decline' AND approved_summary IS NULL))
);
CREATE TABLE IF NOT EXISTS usage_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender TEXT REFERENCES users(sender) ON DELETE SET NULL,
 event_type TEXT NOT NULL CHECK (event_type IN (
 'main_menu_opened','ai_chat_started','resource_hub_opened','resource_category_opened',
 'buddy_search_started','buddy_match_found','buddy_match_unavailable',
 'buddy_application_started','buddy_application_submitted',
 'support_need_selected','profile_suggestion_reviewed')),
 category TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS usage_events_occurred_at ON usage_events(occurred_at);
CREATE INDEX IF NOT EXISTS usage_events_sender_occurred ON usage_events(sender,occurred_at);
CREATE INDEX IF NOT EXISTS usage_events_type_occurred ON usage_events(event_type,occurred_at);

-- Separate, revocable consent for AI-assisted caregiver profiling.
-- This is independent of Support Buddy and information-sharing consent.
CREATE TABLE IF NOT EXISTS caregiver_profiling_consent (
    sender TEXT PRIMARY KEY REFERENCES users(sender) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'not_given'
        CHECK (status IN ('not_given', 'granted', 'declined', 'withdrawn')),
    consent_version TEXT,
    consent_epoch BIGINT NOT NULL DEFAULT 0,
    granted_at TIMESTAMPTZ,
    withdrawn_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (status <> 'granted' OR
           (consent_version IS NOT NULL AND granted_at IS NOT NULL))
);



-- Upgrade older Phase 2 installations without rewriting or deleting profile data.
ALTER TABLE caregiver_profile_suggestions ADD COLUMN IF NOT EXISTS pending_edit_value TEXT;
ALTER TABLE caregiver_profiling_consent ADD COLUMN IF NOT EXISTS consent_epoch BIGINT NOT NULL DEFAULT 0;

-- Prevent simultaneous requests from creating multiple pending suggestions.
CREATE UNIQUE INDEX IF NOT EXISTS
    uq_caregiver_one_pending_suggestion
ON caregiver_profile_suggestions (sender)
WHERE status = 'pending';

-- Durable receipt metadata only: no sender, message body or reply is retained.
CREATE TABLE IF NOT EXISTS whatsapp_receipts (
 message_hash TEXT PRIMARY KEY,
 status TEXT NOT NULL CHECK (status IN ('processing','completed','failed')),
 received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 completed_at TIMESTAMPTZ
);

