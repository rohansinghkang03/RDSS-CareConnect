CREATE TABLE IF NOT EXISTS reporting_settings (
 key TEXT PRIMARY KEY, value TIMESTAMPTZ NOT NULL
);
INSERT INTO reporting_settings VALUES ('coverage_start',CURRENT_TIMESTAMP) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS reporting_people (
 sender TEXT PRIMARY KEY REFERENCES users(sender) ON DELETE CASCADE,
 report_id TEXT UNIQUE NOT NULL,
 first_seen TIMESTAMPTZ,
 observed_since TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_active TIMESTAMPTZ
);
INSERT INTO reporting_people(sender,report_id)
 SELECT sender,'CC-'||md5(random()::text||clock_timestamp()::text||sender) FROM users
 ON CONFLICT(sender) DO NOTHING;
CREATE TABLE IF NOT EXISTS reporting_activity (
 message_hash TEXT PRIMARY KEY, report_id TEXT REFERENCES reporting_people(report_id) ON DELETE SET NULL,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS reporting_activity_time ON reporting_activity(occurred_at);
CREATE TABLE IF NOT EXISTS reporting_facts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id TEXT REFERENCES reporting_people(report_id) ON DELETE SET NULL,
 event TEXT NOT NULL, occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS reporting_facts_time ON reporting_facts(occurred_at,event);
CREATE TABLE IF NOT EXISTS reporting_ai (
 id TEXT PRIMARY KEY, feature TEXT NOT NULL, model TEXT NOT NULL,
 outcome TEXT NOT NULL CHECK(outcome IN ('completed','failed','unknown')),
 input_tokens BIGINT, cached_tokens BIGINT, output_tokens BIGINT,
 service_tier TEXT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(input_tokens IS NULL OR input_tokens>=0),
 CHECK(cached_tokens IS NULL OR cached_tokens BETWEEN 0 AND input_tokens),
 CHECK(output_tokens IS NULL OR output_tokens>=0)
);
CREATE INDEX IF NOT EXISTS reporting_ai_time ON reporting_ai(occurred_at);
CREATE TABLE IF NOT EXISTS reporting_outgoing (
 attempt_id TEXT PRIMARY KEY, provider_id TEXT UNIQUE,
 kind TEXT NOT NULL CHECK(kind IN ('text','document')),
 outcome TEXT NOT NULL CHECK(outcome IN ('attempted','accepted','failed','unknown')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS reporting_outgoing_time ON reporting_outgoing(created_at);
CREATE TABLE IF NOT EXISTS reporting_statuses (
 provider_id TEXT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('sent','delivered','read','failed')),
 occurred_at TIMESTAMPTZ NOT NULL,
 category TEXT, billable BOOLEAN, pricing_model TEXT,
 PRIMARY KEY(provider_id,status)
);
CREATE TABLE IF NOT EXISTS reporting_admin_sessions (
 sender TEXT PRIMARY KEY REFERENCES users(sender) ON DELETE CASCADE,
 credential_version TEXT NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS reporting_login_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sender TEXT NOT NULL REFERENCES users(sender) ON DELETE CASCADE,
 attempted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS reporting_login_window ON reporting_login_attempts(sender,attempted_at);
CREATE TABLE IF NOT EXISTS reporting_jobs (
 id TEXT PRIMARY KEY, sender TEXT NOT NULL REFERENCES users(sender) ON DELETE CASCADE,
 credential_version TEXT NOT NULL,
 start_date DATE NOT NULL, end_date DATE NOT NULL,
 status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','building','sending','sent','failed','review','cancelled')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 provider_id TEXT, CHECK(end_date>=start_date AND end_date-start_date<366)
);
CREATE UNIQUE INDEX IF NOT EXISTS reporting_one_active_job ON reporting_jobs(sender)
 WHERE status IN ('queued','building','sending');
CREATE OR REPLACE FUNCTION reporting_new_person() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO reporting_people(sender,report_id,first_seen)
 VALUES(NEW.sender,'CC-'||md5(random()::text||clock_timestamp()::text||NEW.sender),CURRENT_TIMESTAMP)
 ON CONFLICT DO NOTHING; RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS reporting_new_person ON users;
CREATE TRIGGER reporting_new_person AFTER INSERT ON users FOR EACH ROW EXECUTE FUNCTION reporting_new_person();
CREATE OR REPLACE FUNCTION reporting_profile_fact() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE person TEXT; label TEXT;
BEGIN
 SELECT report_id INTO person FROM reporting_people WHERE sender=NEW.sender;
 IF TG_TABLE_NAME='caregiver_profiling_consent' THEN
  IF TG_OP='UPDATE' AND OLD.status=NEW.status THEN RETURN NEW; END IF;
  label='consent_'||NEW.status;
 ELSE
  IF NEW.status='pending' THEN RETURN NEW; END IF;
  IF TG_OP='UPDATE' AND OLD.status=NEW.status THEN RETURN NEW; END IF;
  label=CASE WHEN NEW.status='rejected' THEN 'profile_rejected'
    WHEN OLD.pending_edit_value IS NOT NULL OR NEW.reviewed_value IS DISTINCT FROM NEW.proposed_value
      THEN 'profile_edited' ELSE 'profile_accepted' END;
 END IF;
 INSERT INTO reporting_facts(report_id,event) VALUES(person,label); RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS reporting_consent_fact ON caregiver_profiling_consent;
CREATE TRIGGER reporting_consent_fact AFTER INSERT OR UPDATE ON caregiver_profiling_consent
 FOR EACH ROW EXECUTE FUNCTION reporting_profile_fact();
DROP TRIGGER IF EXISTS reporting_review_fact ON caregiver_profile_suggestions;
CREATE TRIGGER reporting_review_fact AFTER UPDATE ON caregiver_profile_suggestions
 FOR EACH ROW EXECUTE FUNCTION reporting_profile_fact();
